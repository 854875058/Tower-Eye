def build_matrix_sheet(wb: Workbook):
    ws = wb.create_sheet("能力矩阵")
    ws.append(MATRIX_COLUMNS)
    for row in ROWS:
        ws.append([row[col] for col in MATRIX_COLUMNS])

    sub_fill, _title_font = style_sheet(ws)

    severity_fill = {
        "P0": PatternFill("solid", fgColor="FCE4D6"),
        "P1": PatternFill("solid", fgColor="FFF2CC"),
        "P2": PatternFill("solid", fgColor="E2F0D9"),
    }
    status_fill = {
        "已具备": PatternFill("solid", fgColor="C6E0B4"),
        "部分具备": PatternFill("solid", fgColor="FFE699"),
        "不具备": PatternFill("solid", fgColor="F4CCCC"),
    }

    for row_idx in range(2, ws.max_row + 1):
        ws[f"G{row_idx}"].fill = severity_fill.get(ws[f"G{row_idx}"].value, sub_fill)
        ws[f"H{row_idx}"].fill = status_fill.get(ws[f"H{row_idx}"].value, sub_fill)
        ws[f"N{row_idx}"].number_format = "0.0"


def build_priority_sheet(wb: Workbook):
    ws = wb.create_sheet("优先路线")
    headers = ["阶段", "优先级", "模块", "细分功能", "为什么现在做", "建议输出物", "预计追加工时（人天）"]
    ws.append(headers)

    phase_map = {
        "Phase 1": "能力证明期",
        "Phase 2": "平台增强期",
        "Phase 3": "交付适配期",
    }

    for row in sorted(ROWS, key=lambda item: (item["建议阶段"], item["优先级"], -item["重要程度"].count("高"))):
        if row["建议阶段"] == "Phase 1":
            output = "样机 / 场景 Demo / 方案图"
        elif row["建议阶段"] == "Phase 2":
            output = "平台能力 / 控制台 / 指标体系"
        else:
            output = "交付方案 / 适配说明 / 文档与流程"

        ws.append(
            [
                phase_map.get(row["建议阶段"], row["建议阶段"]),
                row["优先级"],
                row["模块"],
                row["细分功能"],
                row["能力证明切入点"],
                output,
                row["预计追加工时（人天）"],
            ]
        )

    style_sheet(ws)
    ws.column_dimensions["A"].width = 14
    ws.column_dimensions["B"].width = 8
    ws.column_dimensions["C"].width = 18
    ws.column_dimensions["D"].width = 24
    ws.column_dimensions["E"].width = 34
    ws.column_dimensions["F"].width = 22
    ws.column_dimensions["G"].width = 12
    for row_idx in range(2, ws.max_row + 1):
        ws[f"G{row_idx}"].number_format = "0.0"


